#!/usr/bin/env node
/**
 * PupilIOS — Astryx asset build
 *
 * Produces the offline bundle that AstryxWebView loads from the app bundle:
 *
 *   Resources/astryx/astryx.js    React 19 + Astryx components (single IIFE)
 *   Resources/astryx/astryx.css   core reset + astryx.css + theme-neutral theme.css + pupil shim
 *
 * No network is touched at runtime: every url() in the merged CSS is inlined as
 * a data: URI (the theme's Figtree woff2 faces are shipped inside the CSS), and
 * astryx.js is a self-contained IIFE.
 *
 * Run: cd design && npm run build
 */

import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { promises as fs } from 'node:fs';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, '..', 'Resources', 'astryx');

/**
 * Read a package's version by walking up from a resolved entry point.
 * (`<pkg>/package.json` is not exported by every package, so we never import it
 * through the exports map.)
 */
function versionOf(name, probe) {
  let dir = path.dirname(require.resolve(probe));
  for (;;) {
    const candidate = path.join(dir, 'package.json');
    if (existsSync(candidate)) {
      try {
        const json = JSON.parse(readFileSync(candidate, 'utf8'));
        if (json.name === name) return json.version;
      } catch {
        /* keep walking */
      }
    }
    const parent = path.dirname(dir);
    if (parent === dir) return 'unknown';
    dir = parent;
  }
}

const VERSIONS = {
  core: versionOf('@astryxdesign/core', '@astryxdesign/core/astryx.css'),
  theme: versionOf('@astryxdesign/theme-neutral', '@astryxdesign/theme-neutral/theme.css'),
  react: versionOf('react', 'react'),
  reactDom: versionOf('react-dom', 'react-dom/client'),
  stylex: versionOf('@stylexjs/stylex', '@stylexjs/stylex'),
};

const CSS_INPUTS = [
  // Astryx reset (package ships it under src/, see @astryxdesign/core exports)
  { file: require.resolve('@astryxdesign/core/reset.css'), label: 'core/reset.css' },
  // Pre-compiled StyleX CSS for every component
  { file: require.resolve('@astryxdesign/core/astryx.css'), label: 'core/astryx.css' },
  // Font faces for the neutral theme (url() rewritten to data: URIs below)
  { file: require.resolve('@astryxdesign/theme-neutral/fonts.css'), label: 'theme-neutral/fonts.css' },
  // Neutral theme tokens (@scope'd, light-dark() pairs)
  { file: require.resolve('@astryxdesign/theme-neutral/theme.css'), label: 'theme-neutral/theme.css' },
  // Our page shell + iOS 16.0 WKWebView token shim
  { file: path.join(HERE, 'src', 'pupil.css'), label: 'pupil.css (local)' },
];

const MIME = {
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
};

const BANNER = `/*!
 * PupilIOS — Astryx bundle
 * Generated by design/build.mjs — do not edit by hand.
 *
 * Astryx (@astryxdesign/core ${VERSIONS.core}, @astryxdesign/theme-neutral ${VERSIONS.theme})
 *   Copyright (c) Meta Platforms, Inc. and affiliates. MIT License.
 *   https://github.com/meta/astryx
 * React ${VERSIONS.react} / React DOM ${VERSIONS.reactDom} — MIT License.
 * @stylexjs/stylex ${VERSIONS.stylex} — MIT License.
 * Figtree font — SIL Open Font License 1.1 (fonts/LICENSE in @astryxdesign/theme-neutral).
 *
 * PupilIOS itself is GPLv3 (port of codeberg.org/pupil/Pupil).
 */`;

/** Rewrite every relative url(...) in a stylesheet to a data: URI. */
async function inlineUrls(css, cssPath) {
  const dir = path.dirname(cssPath);
  const pattern = /url\(\s*(['"]?)([^'")]+)\1\s*\)/g;
  const jobs = [];
  const seen = new Map();

  for (const match of css.matchAll(pattern)) {
    const ref = match[2];
    if (/^(data:|https?:|#)/i.test(ref)) continue;
    if (seen.has(ref)) continue;
    const abs = path.resolve(dir, ref);
    jobs.push(
      fs.readFile(abs).then((buf) => {
        const mime = MIME[path.extname(abs).toLowerCase()] || 'application/octet-stream';
        seen.set(ref, `data:${mime};base64,${buf.toString('base64')}`);
      }).catch(() => {
        seen.set(ref, null); // report as unresolved, keep original reference
      })
    );
  }
  await Promise.all(jobs);

  const unresolved = [];
  const out = css.replace(pattern, (whole, _q, ref) => {
    if (/^(data:|https?:|#)/i.test(ref)) return whole;
    const dataUri = seen.get(ref);
    if (!dataUri) {
      unresolved.push(ref);
      return whole;
    }
    return `url("${dataUri}")`;
  });
  return { css: out, unresolved };
}

async function buildCss() {
  const chunks = [];
  const report = [];
  const unresolvedAll = [];

  for (const input of CSS_INPUTS) {
    const raw = await fs.readFile(input.file, 'utf8');
    const { css, unresolved } = await inlineUrls(raw, input.file);
    unresolvedAll.push(...unresolved.map((u) => `${input.label}: ${u}`));
    chunks.push(`/* ===== ${input.label} ===== */\n${css}`);
    report.push(`${input.label}  ${raw.length} B -> ${css.length} B`);
  }

  const merged = `${BANNER}\n\n${chunks.join('\n\n')}\n`;

  const external = merged.match(/url\(\s*['"]?(https?:)?\/\//gi);
  const imports = merged.match(/@import\s/gi);
  if (external || imports) {
    throw new Error(
      `Refusing to ship non-offline CSS (external url(): ${external ? external.length : 0}, @import: ${imports ? imports.length : 0})`
    );
  }

  const outFile = path.join(OUT_DIR, 'astryx.css');
  await fs.writeFile(outFile, merged, 'utf8');
  return { outFile, size: Buffer.byteLength(merged), report, unresolvedAll };
}

async function buildJs() {
  const outFile = path.join(OUT_DIR, 'astryx.js');
  await build({
    entryPoints: [path.join(HERE, 'src', 'main.jsx')],
    outfile: outFile,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['safari15'],
    jsx: 'automatic',
    minify: true,
    sourcemap: false,
    legalComments: 'none',
    charset: 'utf8',
    define: {
      'process.env.NODE_ENV': '"production"',
      __ASTRYX_CORE__: JSON.stringify(VERSIONS.core),
      __ASTRYX_THEME__: JSON.stringify(VERSIONS.theme),
      __REACT_VERSION__: JSON.stringify(VERSIONS.react),
      __STYLEX_VERSION__: JSON.stringify(VERSIONS.stylex),
    },
    banner: { js: BANNER },
    logLevel: 'warning',
  });

  const stat = await fs.stat(outFile);
  const text = await fs.readFile(outFile, 'utf8');
  const externalFetch = text.match(/fetch\(\s*['"]https?:/g);
  if (externalFetch) {
    throw new Error(`astryx.js contains ${externalFetch.length} external fetch() call(s)`);
  }
  return { outFile, size: stat.size };
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });

  console.log('Astryx versions:');
  console.log(`  @astryxdesign/core          ${VERSIONS.core}`);
  console.log(`  @astryxdesign/theme-neutral ${VERSIONS.theme}`);
  console.log(`  react / react-dom           ${VERSIONS.react} / ${VERSIONS.reactDom}`);
  console.log(`  @stylexjs/stylex            ${VERSIONS.stylex}`);
  console.log('');

  const js = await buildJs();
  const css = await buildCss();

  for (const line of css.report) console.log(`  css  ${line}`);
  console.log('');

  if (css.unresolvedAll.length > 0) {
    console.log('Unresolved css url() references (left as-is):');
    for (const u of css.unresolvedAll) console.log(`  ! ${u}`);
    console.log('');
  }

  console.log(`wrote ${path.relative(path.resolve(HERE, '..'), js.outFile)}  ${kb(js.size)}`);
  console.log(`wrote ${path.relative(path.resolve(HERE, '..'), css.outFile)}  ${kb(css.size)}`);

  const html = path.join(OUT_DIR, 'pupil-astryx.html');
  try {
    const stat = await fs.stat(html);
    console.log(`found ${path.relative(path.resolve(HERE, '..'), html)}  ${kb(stat.size)} (static, not generated)`);
  } catch {
    console.warn(`WARN: ${html} is missing — AstryxWebView needs it.`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
